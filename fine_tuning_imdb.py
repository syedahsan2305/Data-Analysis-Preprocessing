from transformers import (
    AutoModelForSequenceClassification,
    AutoTokenizer,
    DataCollatorWithPadding,
    TrainingArguments,
    Trainer
)
import numpy as np
from datasets import load_dataset
from peft import LoraConfig, get_peft_model, TaskType
from sklearn.metrics import accuracy_score, precision_recall_fscore_support,confusion_matrix

MODEL_NAME= "google-bert/bert-base-uncased"
dataset = load_dataset('stanfordnlp/imdb')

train_ds = dataset["train"].shuffle(seed=42).select(range(3000))
test_ds = dataset["test"].shuffle(seed=42).select(range(1000))

tokenizer = AutoTokenizer.from_pretrained(MODEL_NAME)

def tokenize_data(batch):
  return tokenizer(batch["text"], max_length=256,truncation=True)

tokenize_train_ds = train_ds.map(tokenize_data, batched=True)
tokenize_test_ds = test_ds.map(tokenize_data, batched=True)

collator = DataCollatorWithPadding(tokenizer=tokenizer)

model = AutoModelForSequenceClassification.from_pretrained(MODEL_NAME, num_labels=2)

config = LoraConfig(
    task_type=TaskType.SEQ_CLS,
    r=8,
    lora_alpha=16,
    lora_dropout = 0.1,
    target_modules = ["query","value"]
)

model = get_peft_model(model, config)
model.print_trainable_parameters()

def compute_metrics(eval_pred):
    logits, labels = eval_pred
    preds = np.argmax(logits, axis=-1)
    precision, recall, f1, _ = precision_recall_fscore_support(labels, preds, average="binary")
    return {
        "accuracy": accuracy_score(labels, preds),
        "precision": precision,
        "recall": recall,
        "f1": f1,
    }

training_args = TrainingArguments(
    output_dir="./lora_results",
    eval_strategy="epoch",
    logging_strategy="epoch",
    save_strategy="no",           # don't fill the Colab disk with checkpoints
    learning_rate=2e-4,           # higher than full fine-tuning (2e-5)
    per_device_train_batch_size=8,
    per_device_eval_batch_size=16,
    num_train_epochs=5,           # same as notebook 1
    weight_decay=0.01,
    fp16=True,
    label_names=["labels"],       # needed so the Trainer passes labels to compute_metrics with a PEFT model
    report_to="none",
)

trainer = Trainer(
    model=model,
    args=training_args,
    train_dataset=tokenize_train_ds,
    eval_dataset=tokenize_test_ds,
    data_collator=collator,
    compute_metrics=compute_metrics
)

train_result = trainer.train()
print("Training time (s):", round(train_result.metrics["train_runtime"], 1))

results = trainer.evaluate()
print(results)

out = trainer.predict(tokenize_test_ds)
preds = np.argmax(out.predictions, axis=-1)
print(confusion_matrix(out.label_ids, preds))

model.save_pretrained("lora_adapter")   # saves only the small adapter weights
