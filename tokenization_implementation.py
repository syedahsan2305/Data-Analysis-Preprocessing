import warnings
warnings.filterwarnings('ignore')
from collections import Counter
from datetime import datetime
import nltk
import spacy
from transformers import BertTokenizer, XLNetTokenizer

nltk.download('punkt')
nltk.download('punkt_tab')

text = """
Going through the world of tokenization has been like walking through a huge maze made of words, symbols, and meanings. Each turn shows a bit more about the cool ways computers learn to understand our language. And while I'm still finding my way through it, the journey’s been enlightening and, honestly, a bunch of fun.
Eager to see where this learning path takes me next!"
"""

def show_frequencies(token,method_name):
  print(f"Method Name: {method_name}, Token Frequency: {dict(Counter(token))}\n")

nlp = spacy.load("en_core_web_sm")
bert_tokenizer = BertTokenizer.from_pretrained("bert-base-uncased")
xlnet_tokenizer = XLNetTokenizer.from_pretrained("xlnet-base-cased")

tokenizers = {
    "NLTK": nltk.word_tokenize,
    "Spacy": lambda t: [token.text for token in nlp(t)],
    "Bert": bert_tokenizer.tokenize,
    "XLnet": xlnet_tokenizer.tokenize
}

results = {}

for name,tokenize in tokenizers.items():
  start_time = datetime.now()
  tokens = tokenize(text)
  elapsed = (datetime.now() - start_time).total_seconds()
  results[name]=(tokens,elapsed)

  print(f"{name} Tokens: {tokens}\nTime Taken: {elapsed:.6f} seconds\n")
  show_frequencies(tokens,name)
  print("-" * 80)